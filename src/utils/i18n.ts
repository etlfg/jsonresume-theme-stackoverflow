let currentLang = "en";

export function setI18nLanguage(lang: string): void {
  switch (lang) {
    case "en-gb":
      currentLang = "en";
      break;
    default:
      currentLang = lang;
  }
}

export function t(key: string): string {
  const lang = resources[currentLang] || resources["en"];
  return lang[key] || resources["en"][key] || key;
}
